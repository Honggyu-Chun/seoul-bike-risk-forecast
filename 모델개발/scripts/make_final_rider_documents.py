class Paper:
    def __init__(self, doc=None, formal=False):
        self.doc = doc or Document()
        self.formal = formal
        self.size = 10.3 if formal else 11.3
        s = self.doc.sections[0]
        s.page_width, s.page_height = Cm(21), Cm(29.7)
        s.top_margin, s.bottom_margin = Cm(1.65), Cm(1.65)
        s.left_margin, s.right_margin = Cm(1.8), Cm(1.8)
        s.header_distance, s.footer_distance = Cm(.7), Cm(.7)
        normal = self.doc.styles['Normal']
        normal.font.name = 'Noto Sans CJK KR'
        normal.font.size = Pt(self.size)
        normal.font.color.rgb = RGBColor.from_string('202020')
        normal._element.get_or_add_rPr().rFonts.set(qn('w:eastAsia'), 'Noto Sans CJK KR')
        normal.paragraph_format.line_spacing = 1.22 if formal else 1.30
        normal.paragraph_format.space_after = Pt(7 if formal else 10)
        normal.paragraph_format.widow_control = True
        hp = s.header.paragraphs[0]
        hp.clear()
        self.run(hp, 'AI P-실무프로젝트  |  따릉이 시민용 서비스  |  실제 데모·실험 반영', 8, color='777777')
        fp = s.footer.paragraphs[0]
        fp.clear(); fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        self.run(fp, '따릉이, 어디로?   ·   ', 8, color='777777')
        field = OxmlElement('w:fldSimple'); field.set(qn('w:instr'), 'PAGE'); fp._p.append(field)

    def run(self, p, text, size=None, bold=False, color='202020'):
        r = p.add_run(str(text)); r.bold = bold; r.font.name = 'Noto Sans CJK KR'
        r.font.size = Pt(size or self.size); r.font.color.rgb = RGBColor.from_string(color)
        r._element.get_or_add_rPr().rFonts.set(qn('w:eastAsia'), 'Noto Sans CJK KR')
        return r

    def para(self, text, bold=False, size=None, after=None):
        p = self.doc.add_paragraph()
        if after is not None: p.paragraph_format.space_after = Pt(after)
        self.run(p, text, size, bold)
        return p

    def page(self, title, first=False):
        p = self.doc.add_paragraph()
        p.paragraph_format.page_break_before = not first
        p.paragraph_format.keep_with_next = True
        p.paragraph_format.space_after = Pt(15)
        pp = p._p.get_or_add_pPr()
        sh = OxmlElement('w:shd'); sh.set(qn('w:fill'), 'E1E1E1'); pp.append(sh)
        self.run(p, '  ' + title, 13 if self.formal else 15, True)

    def h(self, text):
        p = self.para('□ ' + text, True, 11 if self.formal else 12)
        p.paragraph_format.keep_with_next = True
        p.paragraph_format.space_before = Pt(7)

    def bullet(self, label, text):
        p = self.doc.add_paragraph()
        self.run(p, '○ ' + label + '  ', bold=True)
        self.run(p, text)
        return p

    def note(self, text):
        p = self.doc.add_paragraph()
        self.run(p, '※ ' + text, 8.5 if self.formal else 9.3, color='656565')
        return p

    def table(self, headers, rows, widths=None, size=None):
        widths = widths or [17.4/len(headers)] * len(headers)
        t = self.doc.add_table(rows=1, cols=len(headers)); t.autofit=False
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        for c,w in zip(t.columns,widths): c.width=Cm(w)
        for i, vals in enumerate([headers] + list(rows)):
            cells = t.rows[0].cells if i == 0 else t.add_row().cells
            for j, val in enumerate(vals):
                c = cells[j]; c.width=Cm(widths[j]); c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
                p = c.paragraphs[0]
                p.paragraph_format.space_before=Pt(5); p.paragraph_format.space_after=Pt(5)
                p.paragraph_format.line_spacing=1.16
                self.run(p,val,size or (9.2 if self.formal else 10.2),i==0)
                cp=c._tc.get_or_add_tcPr()
                sh=OxmlElement('w:shd'); sh.set(qn('w:fill'),'DDDDDD' if i==0 else ('F3F3F3' if i%2 else 'FFFFFF'));cp.append(sh)
                borders=OxmlElement('w:tcBorders')
                for side in ['top','bottom','left','right']:
                    b=OxmlElement('w:'+side)
                    for k,v in [('val','single'),('sz','3'),('color','C8C8C8')]:b.set(qn('w:'+k),v)
                    borders.append(b)
                cp.append(borders)
            trp=t.rows[i]._tr.get_or_add_trPr();trp.append(OxmlElement('w:cantSplit'))
            if i==0:trp.append(OxmlElement('w:tblHeader'))
        self.para('',after=0,size=1)
        return t

    def box(self, title, text): self.table([title],[(text,)],[17.4])

    def picture(self, path, caption, width=16.8):
        p=self.doc.add_paragraph();p.alignment=WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after=Pt(3)
        p.add_run().add_picture(str(path),width=Cm(width))
        self.note(caption)

    def save(self, name):
        target=ROOT.parent/'과제제안서/이전작성본' if ('과제계획서' in name or '과제제안서' in name) else OUT
        target.mkdir(parents=True,exist_ok=True)
        path=target/name;self.doc.save(path);print(path)
        return path


